using System.Text.Json;
using HelixCrm.Api.Data;
using HelixCrm.Api.Domain;
using Microsoft.EntityFrameworkCore;

namespace HelixCrm.Api.Features.Config;

public interface IAutomationEngine
{
    Task TriggerAsync(string eventType, string entityType, Guid entityId, string title, Guid? ownerId = null);
}

public class AutomationEngine(HelixDbContext db, ILogger<AutomationEngine> logger) : IAutomationEngine
{
    public async Task TriggerAsync(string eventType, string entityType, Guid entityId, string title, Guid? ownerId = null)
    {
        try
        {
            var rules = await db.AutomationRules
                .Where(r => r.EventType == eventType && r.IsActive)
                .ToListAsync();

            if (rules.Count == 0) return;

            var now = DateTime.UtcNow;

            foreach (var rule in rules)
            {
                rule.ExecutionCount++;

                if (rule.ActionType == "CreateTask")
                {
                    var subject = $"Follow-up: {title}";
                    var dueDays = 1;

                    try
                    {
                        using var doc = JsonDocument.Parse(rule.ActionConfigJson);
                        if (doc.RootElement.TryGetProperty("taskSubject", out var subjProp) && !string.IsNullOrWhiteSpace(subjProp.GetString()))
                        {
                            subject = subjProp.GetString()!.Replace("{title}", title);
                        }
                        if (doc.RootElement.TryGetProperty("durationDays", out var daysProp))
                        {
                            dueDays = daysProp.GetInt32();
                        }
                    }
                    catch
                    {
                        // fallback to defaults
                    }

                    db.Activities.Add(new Activity
                    {
                        OrganizationId = rule.OrganizationId,
                        Type = ActivityType.Task,
                        Subject = subject,
                        Body = $"Auto-generated by automation rule: {rule.Name}",
                        DueAt = now.AddDays(dueDays),
                        Priority = "Normal",
                        RelatedType = entityType,
                        RelatedId = entityId,
                        OwnerId = ownerId,
                        Status = ActivityStatus.Open
                    });
                }
                else if (rule.ActionType == "SendNotification")
                {
                    var notifTitle = $"Automation: {rule.Name}";
                    var notifBody = $"{eventType} triggered for {title}";

                    var targetUserId = ownerId;
                    if (targetUserId == null)
                    {
                        targetUserId = await db.Users
                            .Where(u => u.Role == Roles.Admin && u.IsActive)
                            .Select(u => (Guid?)u.Id)
                            .FirstOrDefaultAsync();
                    }

                    if (targetUserId != null)
                    {
                        db.Notifications.Add(new Notification
                        {
                            OrganizationId = rule.OrganizationId,
                            UserId = targetUserId.Value,
                            Title = notifTitle,
                            Body = notifBody,
                            Link = $"/{entityType.ToLower()}s/{entityId}",
                            Type = "info"
                        });
                    }
                }
            }

            await db.SaveChangesAsync();
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Failed to execute automations for {Event} on {EntityType}:{EntityId}", eventType, entityType, entityId);
        }
    }
}

